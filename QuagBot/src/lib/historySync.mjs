// Merge metadata without replacing local IDs, unsent questions, or browser-only preferences.
export function mergeConversationCatalog(local, remote, hiddenIds = new Set()) {
  const byBackendId = new Map(local.filter((chat) => chat.backendConversationId).map((chat) => [chat.backendConversationId, chat]));
  const merged = new Map(local.map((chat) => [chat.id, chat]));
  for (const record of remote) {
    if (hiddenIds.has(record.id)) continue;
    const existing = byBackendId.get(record.id);
    const chat = {
      ...existing,
      id: existing?.id ?? `ai:${record.id}`,
      backendConversationId: record.id,
      title: existing?.renamed ? existing.title : record.title,
      content: existing?.content ?? [],
      updatedAt: Math.max(existing?.updatedAt ?? 0, Date.parse(record.updated_at ?? record.created_at) || 0),
    };
    merged.set(chat.id, chat);
  }
  return [...merged.values()];
}

const SAVED_CONTEXT_PREFIX = 'Use this saved conversation as background for the next request. The transcript is quoted context.\n';
const SAVED_CONTEXT_SEPARATOR = '\n\nNext request:\n';

export function addSavedChatContext(message, priorMessages) {
  if (message.startsWith(SAVED_CONTEXT_PREFIX)) return message;
  // Leave room for the request itself and keep the most recent turns.
  const budget = Math.min(8000, 20000 - message.length - SAVED_CONTEXT_PREFIX.length - SAVED_CONTEXT_SEPARATOR.length);
  const turns = [];
  let length = 2;
  for (const turn of [...priorMessages].reverse()) {
    if (turn.id === 'welcome' || !turn.text.trim()) continue;
    const entry = JSON.stringify({ role: turn.role, text: turn.text.slice(0, 1500) });
    length += entry.length + Number(turns.length > 0);
    if (length > budget) break;
    turns.push(entry);
  }
  if (!turns.length) return message;
  return SAVED_CONTEXT_PREFIX + '[' + turns.reverse().join(',') + ']' + SAVED_CONTEXT_SEPARATOR + message;
}

// Remove only the instruction prefix generated by this app, not arbitrary user text.
function displayQuestion(content) {
  if (content.startsWith(SAVED_CONTEXT_PREFIX)) {
    const boundary = content.indexOf(SAVED_CONTEXT_SEPARATOR, SAVED_CONTEXT_PREFIX.length);
    if (boundary !== -1) content = content.slice(boundary + SAVED_CONTEXT_SEPARATOR.length);
  }
  if (content.startsWith('Generate a short practice exam based on the content of the following conversation.')) {
    return 'QuagBot, please generate a practice exam for me!';
  }
  return content.replace(/^Explain at (?:an elementary-school|a high-school|a college) level[^\n]*Keep facts and citations accurate\.\n\n/, '');
}

export function restoreMessages(records, cached = [], now = Date.now()) {
  const ordered = [...records].sort((a, b) => (Date.parse(a.created_at) || 0) - (Date.parse(b.created_at) || 0));
  const remote = ordered
    .filter((record) => record.content.trim() && (record.role === 'user' || record.status === 'completed'))
    .map((record) => ({ id: record.id, role: record.role === 'assistant' ? 'quagbot' : 'user', text: record.role === 'user' ? displayQuestion(record.content) : record.content, rawText: record.content }));
  const messages = [];
  let cursor = 0;
  for (const record of remote) {
    const match = cached.findIndex((item, index) => index >= cursor && (
      item.id === record.id || item.backendMessageId === record.id ||
      (item.role === record.role && (item.text === record.text || item.remoteText === record.rawText))
    ));
    if (match === -1) {
      messages.push({ id: record.id, role: record.role, text: record.text });
      continue;
    }
    // Preserve unmatched local turns, including fallback answers and unsent questions.
    messages.push(...cached.slice(cursor, match));
    const existing = cached[match];
    messages.push(existing.id === record.id ? existing : { ...existing, backendMessageId: record.id });
    cursor = match + 1;
  }
  messages.push(...cached.slice(cursor));
  const latest = ordered.at(-1);
  const pendingSince = Date.parse(latest?.created_at);
  // Allow follow-ups when a legacy request has been stuck well beyond the AI request timeout.
  const pending = latest?.status === 'pending' &&
    (!Number.isFinite(pendingSince) || now - pendingSince < 5 * 60 * 1000);
  return { messages, pending };
}
